-- TCL - TRANSAÇÃO E INTEGRIDADES
-- EX 1: TRANSAÇAO PARA RESOLVER PROBLEMAS
-- SEM TRANSAÇÃO: PARTE PODE PERMANECER GRAVADA
-- COM TRANSAÇAO: PODE CONFIRMAR TUDO OU DESFAZER TUDO

-- ESTRUTURA DO CONCEITO
START TRANSACTION; -- INICIA UMA TRANSAÇÃO
-- COMANDOS SQL
-- INSERT, UPDATE,DELETE,SELECT
COMMIT; --CONFITMA TODAS AS ALTERAÇOES
ROLLBACK; -- DESFAZ TODAS AS ALTERAÇOES

-- EX2: COMMIT - CONFIRMA ALTERACOES REALIZADAS
START TRANSACTION;
SELECT * FROM produto WHERE id_PRODUTO = 1;
UPDATE produto
SET preco = preco * 9.00
WHERE id_produto = 1;
SELECT * FROM produto WHERE id_PRODUTO = 1;
COMMIT;

-- EX3: ROLLBACK - DESFAZ ALTERACOES AINDA NÃO CONFIRMADAS
START TRANSACTION;
SELECT * FROM produto WHERE id_PRODUTO = 1;
UPDATE produto
SET preco = 5000.00
WHERE id_produto = 1;
SELECT * FROM produto WHERE id_PRODUTO = 1;
ROLLBACK;

-- EX4: SAVAPOINT - CRIAR UM PONTO DE SALVAMENTO OU CHECKPOINT DE UMA TRANSACÃO
START TRANSACTION;
UPDATE produto
SET preco = preco * 1.05
WHERE id_categoria = 1;

SAVEPOINT REAJUSTE_CAFES;

SELECT * FROM produto WHERE id_categoria = 1;
UPDATE produto
SET preco = preco * 1.50
WHERE id_categoria = 1;

ROLLBACK TO SAVEPOINT REAJUSTE_CAFES;
COMMIT;

-- EX 5: RELEASE SEVEPOINT -REMOVER O SAVEPOINT CRIADO ANTERIORMENTE
RELEASE SAVEPOINT REAJUSTE_CAFES;
